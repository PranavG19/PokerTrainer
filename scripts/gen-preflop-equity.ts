/**
 * Generate src/core/pro/preflopEquity.data.ts: the all-in preflop equity of every starting-hand class
 * against every other, card removal included, by seeded Monte Carlo over the evaluator.
 *
 *   node --import ./scripts/ts-js-resolve.mjs scripts/gen-preflop-equity.ts [samples-per-pair]
 *
 * Each pair (a, b) with a < b samples a concrete hand of each that share no card, uniformly over the
 * compatible pairs, and a five-card board from the 48 left. Equity = wins + ties / 2. The table is
 * antisymmetric (E[b][a] = 1 - E[a][b]) and E[a][a] = 1/2 by symmetry, so only a < b is stored, as
 * three base-64 digits per pair (0..10000 = 0.01% steps). Deterministic: same seed, same file.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { mulberry32 } from '../src/core/rng.ts';
import { score } from '../src/core/pro/eval7.ts';
import { CLASS_COUNT, CLASS_HANDS } from '../src/core/pro/handClasses.ts';
import { encodeTable, TABLE_ALPHABET } from '../src/core/pro/preflopEquityCodec.ts';

const samples = Number(process.argv[2] ?? 100000);
const SEED = 20261014;
const rng = mulberry32(SEED);

const values: number[] = [];
const seven = new Int32Array(7);
const other = new Int32Array(7);
const deck = new Int32Array(52);
const started = Date.now();
for (let a = 0; a < CLASS_COUNT; a++) {
  for (let b = a + 1; b < CLASS_COUNT; b++) {
    const pairs: [number, number, number, number][] = [];
    for (const [x0, x1] of CLASS_HANDS[a]) {
      for (const [y0, y1] of CLASS_HANDS[b]) {
        if (x0 !== y0 && x0 !== y1 && x1 !== y0 && x1 !== y1) pairs.push([x0, x1, y0, y1]);
      }
    }
    let won = 0;
    for (let s = 0; s < samples; s++) {
      const [x0, x1, y0, y1] = pairs[Math.floor(rng() * pairs.length)];
      let n = 0;
      for (let c = 0; c < 52; c++) if (c !== x0 && c !== x1 && c !== y0 && c !== y1) deck[n++] = c;
      for (let k = 0; k < 5; k++) {
        const j = k + Math.floor(rng() * (n - k));
        const t = deck[k];
        deck[k] = deck[j];
        deck[j] = t;
        seven[k + 2] = deck[k];
        other[k + 2] = deck[k];
      }
      seven[0] = x0;
      seven[1] = x1;
      other[0] = y0;
      other[1] = y1;
      const h = score(seven, 7);
      const v = score(other, 7);
      won += h > v ? 2 : h === v ? 1 : 0;
    }
    values.push(Math.round((won / (2 * samples)) * 10000));
  }
  process.stderr.write(`\r${a + 1}/${CLASS_COUNT} classes, ${Math.round((Date.now() - started) / 1000)}s`);
}
process.stderr.write('\n');

const out = path.join(import.meta.dirname, '../src/core/pro/preflopEquity.data.ts');
const encoded = encodeTable(values);
const lines: string[] = [];
for (let i = 0; i < encoded.length; i += 120) lines.push(`  '${encoded.slice(i, i + 120)}',`);
fs.writeFileSync(
  out,
  `/**
 * GENERATED by scripts/gen-preflop-equity.ts (${samples} samples per pair, seed ${SEED}). Do not edit.
 * The upper triangle (a < b, ALL_COMBOS order) of the preflop all-in equity table, three digits of
 * '${TABLE_ALPHABET.slice(0, 8)}…' per pair in 0.01% steps. Decoded by preflopEquity.ts.
 */
export const PREFLOP_EQUITY_SAMPLES = ${samples};
export const PREFLOP_EQUITY_DATA = [
${lines.join('\n')}
].join('');
`,
);
console.log(`wrote ${out} (${values.length} pairs)`);
