/**
 * Generates src/core/preflopStrength.ts: each of the 169 starting hands' pot share against one random
 * hand, preflop. Run from the repo root:
 *   ./node_modules/.bin/vite-node scripts/grader/gen-preflop-strength.ts [iterations]
 * Deterministic (seed 20261012). At 100k iterations the standard error is about 0.15 points.
 */
import { writeFileSync } from 'node:fs';
import { ALL_COMBOS } from '../../src/core/preflop.js';
import { equityVsRandom, scalarEquity } from '../../src/core/equity.js';

const iterations = Number(process.argv[2] ?? 100_000);
const sample = (combo: string): [string, string] => {
  const [hi, lo] = [combo[0], combo[1]];
  if (hi === lo) return [`${hi}s`, `${lo}h`];
  return combo[2] === 's' ? [`${hi}s`, `${lo}s`] : [`${hi}s`, `${lo}h`];
};
const rows = ALL_COMBOS.map((c) => `  ${JSON.stringify(c)}: ${scalarEquity(equityVsRandom(sample(c), [], 1, iterations, 20261012)).toFixed(4)},`);
writeFileSync(
  'src/core/preflopStrength.ts',
  `/**
 * GENERATED by scripts/grader/gen-preflop-strength.ts (${iterations} iterations per hand, seed 20261012).
 * Do not edit by hand. Each starting hand's pot share (win + tie/2) against one random hand, preflop: the
 * same "strength" scale the archetypes decide on (archetypes.ts handStrength), measured precisely once
 * instead of at 300 noisy iterations. villainRanges.ts reads it for preflop ranges and the preflop filter.
 */
import type { Combo } from './preflop.js';

export const PREFLOP_STRENGTH: Readonly<Record<Combo, number>> = {
${rows.join('\n')}
};
`,
);
